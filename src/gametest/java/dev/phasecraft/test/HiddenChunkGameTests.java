package dev.phasecraft.test;

import dev.phasecraft.layer.HiddenLayer;
import dev.phasecraft.link.HiddenChunks;
import net.fabricmc.fabric.api.gametest.v1.GameTest;
import net.minecraft.core.BlockPos;
import net.minecraft.gametest.framework.GameTestHelper;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.entity.EntitySpawnReason;
import net.minecraft.world.entity.EntityTypes;
import net.minecraft.world.entity.decoration.ArmorStand;
import net.minecraft.world.level.ChunkPos;
import net.minecraft.world.level.block.Blocks;

/**
 * Hidden chunks load and tick only where they hold something (HiddenChunks): an empty hidden twin of a ticking
 * visible chunk is never loaded, and one that gets a block or a hidden entity starts ticking as its twin does. Each
 * test works far from the others, around a visible chunk it keeps loaded itself, at a random place (the index is
 * saved with the world).
 */
public class HiddenChunkGameTests {
    private static ChunkPos farChunk(GameTestHelper helper) {
        var random = helper.getLevel().getRandom();
        return new ChunkPos(20_000 + random.nextInt(100_000), 20_000 + random.nextInt(100_000));
    }

    /**
     * Keeps a visible chunk loaded and ticking, generating it and the chunks around it now: a far chunk generated by
     * the ticket alone can take longer than a test's ticks, which run back to back when few tests do.
     */
    private static void force(ServerLevel visible, ChunkPos chunk) {
        generate(visible, chunk);
        visible.setChunkForced(chunk.x(), chunk.z(), true);
    }

    /** Generates the chunks around one now (a hidden one too, once it may be loaded: its ticket then acts at once). */
    private static void generate(ServerLevel level, ChunkPos chunk) {
        for (int dx = -2; dx <= 2; dx++) {
            for (int dz = -2; dz <= 2; dz++) {
                level.getChunk(chunk.x() + dx, chunk.z() + dz);
            }
        }
    }

    private static BlockPos middle(ChunkPos chunk, int y) {
        return new BlockPos(chunk.getMinBlockX() + 8, y, chunk.getMinBlockZ() + 8);
    }

    /** An empty hidden chunk stays unloaded under its ticking twin; a block in it, and it ticks: hidden sand falls. */
    @GameTest(maxTicks = 1200)
    public void anEmptyHiddenChunkLoadsOnlyOnceItHoldsSomething(GameTestHelper helper) {
        ServerLevel visible = helper.getLevel();
        HiddenLayer layer = HiddenLayer.of(visible);
        ServerLevel hidden = layer.level();
        ChunkPos chunk = farChunk(helper);
        BlockPos floor = middle(chunk, 80);
        force(visible, chunk);
        helper.startSequence()
                .thenWaitUntil(() -> helper.assertTrue(visible.isPositionEntityTicking(floor), "the visible chunk ticks"))
                .thenIdle(20)
                .thenExecute(() -> {
                    helper.assertValueEqual(HiddenChunks.ticketRadius(hidden, chunk.x(), chunk.z()), 0,
                            "the ticket of an empty hidden chunk under its ticking twin");
                    helper.assertTrue(hidden.getChunkSource().getChunkNow(chunk.x(), chunk.z()) == null,
                            "an empty hidden chunk was loaded for its ticking twin");
                    helper.assertFalse(HiddenChunks.mayHold(hidden, chunk.x(), chunk.z()), "an empty hidden chunk is listed");
                    generate(hidden, chunk);
                    layer.setBlock(floor, Blocks.STONE.defaultBlockState());
                    layer.setBlock(floor.above(6), Blocks.SAND.defaultBlockState());
                    helper.assertTrue(HiddenChunks.mayHold(hidden, chunk.x(), chunk.z()), "a hidden chunk with blocks is not listed");
                })
                // A scheduled tick (sand starts to fall) and an entity tick (it falls and lands): the chunk ticks.
                .thenWaitUntil(() -> helper.assertValueEqual(layer.getBlock(floor.above()).getBlock(), Blocks.SAND,
                        "the hidden sand landed on the hidden stone"))
                .thenExecute(() -> {
                    layer.removeBlock(floor);
                    layer.removeBlock(floor.above());
                    visible.setChunkForced(chunk.x(), chunk.z(), false);
                })
                .thenSucceed();
    }

    /** A hidden entity in an empty hidden chunk (next to one that ticks) makes it tick: it is not left frozen there. */
    @GameTest(maxTicks = 1200)
    public void aHiddenEntityKeepsItsChunkTicking(GameTestHelper helper) {
        ServerLevel visible = helper.getLevel();
        HiddenLayer layer = HiddenLayer.of(visible);
        ServerLevel hidden = layer.level();
        ChunkPos built = farChunk(helper);
        ChunkPos beside = new ChunkPos(built.x() + 1, built.z());
        BlockPos block = middle(built, 80);
        BlockPos stand = middle(beside, 81);
        force(visible, built);
        force(visible, beside);
        helper.startSequence()
                .thenWaitUntil(() -> helper.assertTrue(visible.isPositionEntityTicking(block) && visible.isPositionEntityTicking(stand),
                        "the visible chunks tick"))
                .thenExecute(() -> {
                    generate(hidden, built);
                    layer.setBlock(block, Blocks.STONE.defaultBlockState());
                })
                .thenWaitUntil(() -> helper.assertTrue(hidden.isPositionEntityTicking(block), "the hidden chunk with a block ticks"))
                .thenExecute(() -> {
                    helper.assertFalse(HiddenChunks.mayHold(hidden, beside.x(), beside.z()), "the empty chunk beside it is listed");
                    helper.assertFalse(hidden.isPositionEntityTicking(stand), "the empty chunk beside it ticks entities");
                    ArmorStand entity = EntityTypes.ARMOR_STAND.create(hidden, EntitySpawnReason.COMMAND);
                    entity.setNoGravity(true);
                    entity.snapTo(stand.getX() + 0.5, stand.getY(), stand.getZ() + 0.5);
                    hidden.addFreshEntity(entity);
                })
                .thenWaitUntil(() -> helper.assertTrue(hidden.isPositionEntityTicking(stand),
                        "the hidden chunk the entity is in does not tick entities"))
                .thenExecute(() -> {
                    hidden.getEntitiesOfClass(ArmorStand.class, new net.minecraft.world.phys.AABB(stand).inflate(2)).forEach(e -> e.discard());
                    layer.removeBlock(block);
                    visible.setChunkForced(built.x(), built.z(), false);
                    visible.setChunkForced(beside.x(), beside.z(), false);
                })
                .thenSucceed();
    }

    /**
     * A hidden chunk emptied while its twin ticks drops out of the index when its twin stops ticking, and is not
     * loaded again when the twin ticks again.
     */
    @GameTest(maxTicks = 1200)
    public void anEmptiedHiddenChunkIsLeftUnloaded(GameTestHelper helper) {
        ServerLevel visible = helper.getLevel();
        HiddenLayer layer = HiddenLayer.of(visible);
        ServerLevel hidden = layer.level();
        ChunkPos chunk = farChunk(helper);
        BlockPos at = middle(chunk, 80);
        force(visible, chunk);
        helper.startSequence()
                .thenWaitUntil(() -> helper.assertTrue(visible.isPositionEntityTicking(at), "the visible chunk ticks"))
                .thenExecute(() -> {
                    generate(hidden, chunk);
                    layer.setBlock(at, Blocks.STONE.defaultBlockState());
                })
                .thenWaitUntil(() -> helper.assertTrue(hidden.isPositionEntityTicking(at), "the hidden chunk with a block ticks"))
                .thenExecute(() -> {
                    layer.removeBlock(at);
                    visible.setChunkForced(chunk.x(), chunk.z(), false);
                })
                .thenWaitUntil(() -> helper.assertFalse(HiddenChunks.mayHold(hidden, chunk.x(), chunk.z()),
                        "the emptied hidden chunk is still listed after its twin stopped ticking"))
                .thenWaitUntil(() -> helper.assertTrue(hidden.getChunkSource().getChunkNow(chunk.x(), chunk.z()) == null,
                        "the emptied hidden chunk unloads"))
                .thenExecute(() -> visible.setChunkForced(chunk.x(), chunk.z(), true))
                .thenWaitUntil(() -> helper.assertTrue(visible.isPositionEntityTicking(at), "the visible chunk ticks again"))
                .thenIdle(20)
                .thenExecute(() -> {
                    helper.assertValueEqual(HiddenChunks.ticketRadius(hidden, chunk.x(), chunk.z()), 0,
                            "the ticket of the emptied hidden chunk under its ticking twin");
                    helper.assertTrue(hidden.getChunkSource().getChunkNow(chunk.x(), chunk.z()) == null,
                            "the emptied hidden chunk was loaded again for its twin");
                    visible.setChunkForced(chunk.x(), chunk.z(), false);
                })
                .thenSucceed();
    }
}
